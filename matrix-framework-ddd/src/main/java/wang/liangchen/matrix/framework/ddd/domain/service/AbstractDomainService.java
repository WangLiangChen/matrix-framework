package wang.liangchen.matrix.framework.ddd.domain.service;

import wang.liangchen.matrix.framework.ddd.domain.DomainMetaModel;
import wang.liangchen.matrix.framework.ddd.domain.DomainModel;

/**
 * 领域服务抽象基类，为领域服务提供标记与骨架支持。
 * <p>
 * <b>一、本质</b>
 * <ul>
 *   <li>领域服务本身可以表达一个重要的<b>领域概念</b>（领域过程），以统一语言命名，
 *       不仅仅是行为的兜底归属。当一个领域行为本质上是一个领域过程，
 *       而非某个实体或值对象的职责时，应将其建模为领域服务。</li>
 *   <li>领域服务的方法应<b>细粒度</b>，每个方法表达一个明确的领域职责，
 *       不应将多个不相关的领域行为塞入同一个方法。</li>
 * </ul>
 * <p>
 * <b>二、核心职责</b>
 * <ul>
 *   <li>承载无法自然归属到任何实体或值对象的领域行为——当行为需要协调多个聚合、
 *       或需要访问领域仓储等外部资源端口时，领域服务是合理的归属。</li>
 *   <li>协调跨聚合的业务行为：一次事务只修改一个聚合实例，跨聚合的状态变更
 *       通过领域事件或应用层编排实现最终一致性；领域服务可在同一事务内
 *       协调同一限界上下文内多个聚合的瞬态协作。</li>
 *   <li>方法命名应体现业务语义（动词短语），遵循统一语言。</li>
 * </ul>
 * <p>
 * <b>三、引入条件</b>
 * <ul>
 *   <li>引入：业务行为无法归属到任何实体或值对象；或行为代表一个重要的领域过程；
 *       或行为需要协调多个聚合；或行为需要访问领域仓储（聚合内部不得使用仓储）。</li>
 *   <li>不引入：行为可归属实体或值对象；仅包含技术操作（校验、存储、消息发送应放入应用服务或适配器）。</li>
 * </ul>
 * <p>
 * <b>四、使用原则</b>
 * <ul>
 *   <li>应<b>克制使用</b>：领域行为优先归属实体或值对象，避免业务逻辑外溢导致贫血模型。
 *       只有在实体与值对象均无法承担时，才将行为放入领域服务。</li>
 *   <li>应为<b>无状态</b>：不持有业务数据，不维护业务状态。领域服务的意义在于表达一个
 *       领域行为或领域概念，而非持有数据。</li>
 *   <li>不应成为<b>过程式编程的退路</b>：不应将所有逻辑放在服务方法中形成事务脚本，
 *       而应让实体和值对象承担尽可能多的行为，领域服务仅协调与编排。</li>
 *   <li>可依赖领域仓储及其它领域服务，但不应依赖应用层与基础设施层细节。</li>
 *   <li>领域服务是框架 ArchUnit 规则中唯一豁免端口依赖的领域模型类——
 *       聚合/实体/值对象/事件/工厂均不得依赖端口，领域服务可依赖领域仓储。</li>
 * </ul>
 * <p>
 * <b>五、约束</b>
 * <ul>
 *   <li>实现类必须自行标注 @DomainModel(DomainMetaModel.DomainService)
 *       （@DomainModel 无 @Inherited，标注不会沿继承传播）。</li>
 *   <li>不得将业务逻辑大量外溢到领域服务，否则形成贫血模型——
 *       领域对象只有属性没有行为，业务逻辑散落在服务层。</li>
 *   <li>互为协作的领域行为，由调用者将另一领域对象作为参数传入来参与实现领域逻辑，
 *       而非在领域服务中直接操作对方的内部状态。</li>
 * </ul>
 *
 * @author Liangchen.Wang
 */
@DomainModel(DomainMetaModel.DomainService)
public abstract class AbstractDomainService implements IDomainService {

}